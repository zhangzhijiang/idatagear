#!/usr/bin/env python3
"""Pre-publish checks for the idatagear.com redesign.

    python3 tools/check_site.py            # compare against the main branch
    python3 tools/check_site.py --base REF # compare against another ref

Fails (exit 1) when:
  1. a protected file differs from the base ref: the privacy, terms and
     deletion pages (generated by documents/privacy/tools/build_privacy.py, and
     registered with the app stores), the stylesheets and scripts those pages
     load, the Flutter web apps, and the store-verification files;
  2. a page or text file this site owns promises a price: "free", "ad-free",
     "no subscription" and the rest, in English or Chinese, including
     schema.org offers/price (see the global CLAUDE.md);
  3. a link, image, video, poster or caption track points at a file that does
     not exist, or an in-page #anchor has no matching id;
  4. a JSON-LD block does not parse;
  5. sitemap.xml lists a URL with no file behind it, or leaves out a page;
  6. a promo video is over budget or not encoded with the index up front;
  7. the shared head, header or footer has drifted from tools/partials/.
Standard library only.
"""
import fnmatch
import json
import os
import re
import subprocess
import sys
from urllib.parse import urlparse, unquote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://www.idatagear.com"
sys.path.insert(0, os.path.join(ROOT, "tools"))
import sync_partials  # noqa: E402

# 1. Files that must stay byte-identical to the base ref.
PROTECTED = [
    "privacy*.html", "privacy-policy-*.html", "*/*_privacy.html", "*/privacy_*.html", "*/terms_*.html",
    "quickone_scanner/*", "mccards/*", "*-delete.html",
    "assets/css/style.css", "assets/css/help.css", "assets/js/main.js", "assets/vendor/bootstrap/*",
    "assets/vendor/bootstrap-icons/*", "assets/vendor/aos/*", "assets/vendor/boxicons/*", "assets/img/*",
    "cantonese/learncantonese/*", "chinese/learnchinese/*", "english/learnenglish/*",
    "gcd/*", "xiezi/*", "hiking/*", "eyeballit/*", "interview/*", "tttt/*", "siding/*",
    "ads.txt", "app-ads.txt", "cantonese/app-ads.txt", "CNAME", ".nojekyll", "google*.html", "404*.html", "firebase.json",
]
# New files the redesign adds inside otherwise-protected folders.
PROTECTED_EXCEPT = ["gcd/guide/*", "xiezi/guide/*", "assets/img/apps/*", "assets/img/og/*", "assets/img/brand/*"]

# 2. Price and availability promises. "hands-free" is a feature, and the Play
#    Store's own "Payments & subscriptions" menu is a navigation path.
FORBIDDEN = re.compile(
    r"(?<!hands-)\bfree\b|ad-free|\bno ads\b|\bads?-supported\b|remove ads|\bno subscription|\bsubscription-free\b"
    r"|paywall|one-time purchase|one-off purchase|\bpremium\b|US\$|\$\d|\bprice[sd]?\b|\bpricing\b|watermark"
    r"|免费|免費|没有广告|沒有廣告|无广告|無廣告|去广告|去廣告|没有订阅|沒有訂閱|无需订阅|無需訂閱|一次性购买|一次性購買"
    r'|"offers"|"price"',
    re.I)
ALLOWED = [re.compile(p, re.I) for p in (r"Payments (&amp;|&) subscriptions",)]
OWNED_TEXT = ["llms.txt", "llms-full.txt", "sitemap.xml", "robots.txt",
              "tools/partials/head.html", "tools/partials/header.html", "tools/partials/footer.html"]

VIDEO_BUDGET = 5 * 1024 * 1024
ATTRS = re.compile(r'\b(?:href|src|poster|data-src|data-poster|data-track|data-before|data-after|data-href)="([^"]*)"')
SRCSET = re.compile(r'\bsrcset="([^"]*)"')


def git(*args):
    return subprocess.run(["git", "-C", ROOT, *args], capture_output=True, text=True, check=True).stdout


def matches(path, patterns):
    return any(fnmatch.fnmatch(path, p) for p in patterns)


def check_protected(base, errors):
    changed = git("diff", "--name-status", "--no-renames", base).splitlines()
    for line in changed:
        status, path = line.split("\t", 1)
        if matches(path, PROTECTED) and not matches(path, PROTECTED_EXCEPT):
            errors.append("protected file %s: %s" % ({"M": "modified", "D": "deleted"}.get(status, status), path))


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return fh.read()


def check_copy(rel, text, errors):
    for n, line in enumerate(text.splitlines(), 1):
        for pat in ALLOWED:
            line = pat.sub("", line)
        for m in FORBIDDEN.finditer(line):
            errors.append("%s:%d: price wording %r" % (rel, n, m.group(0)))


def local_target(page_rel, url):
    """Map a link to the repo file it should resolve to, or None if external."""
    if url.startswith(SITE):
        url = url[len(SITE):] or "/"
    p = urlparse(url)
    if p.scheme or url.startswith("//"):
        return None
    path = unquote(p.path)
    if not path:
        return None
    if path.startswith("/"):
        target = path.lstrip("/")
    else:
        target = os.path.normpath(os.path.join(os.path.dirname(page_rel), path))
    if target in ("", ".") or path.endswith("/"):
        target = os.path.join(target, "index.html") if target not in ("", ".") else "index.html"
    return target


def check_links(rel, text, errors):
    ids = set(re.findall(r'\bid="([^"]+)"', text))
    urls = ATTRS.findall(text)
    for s in SRCSET.findall(text):
        urls += [part.strip().split(" ")[0] for part in s.split(",")]
    urls += re.findall(r'<meta (?:property|name)="(?:og|twitter):image" content="([^"]*)"', text)
    for url in urls:
        if url.startswith(("mailto:", "tel:", "javascript:")):
            continue
        if url.startswith("#"):
            if url != "#" and url[1:] not in ids:
                errors.append("%s: anchor %s has no matching id" % (rel, url))
            continue
        target = local_target(rel, url)
        if target and not os.path.exists(os.path.join(ROOT, target)):
            errors.append("%s: broken link %s" % (rel, url))


def check_jsonld(rel, text, errors):
    for block in re.findall(r'<script type="application/ld\+json">(.*?)</script>', text, re.S):
        try:
            json.loads(block)
        except ValueError as e:
            errors.append("%s: JSON-LD does not parse (%s)" % (rel, e))


def check_sitemap(errors):
    locs = re.findall(r"<loc>([^<]*)</loc>", read("sitemap.xml"))
    for loc in locs:
        target = local_target("sitemap.xml", loc)
        if not target or not os.path.exists(os.path.join(ROOT, target)):
            errors.append("sitemap.xml: %s has no file behind it" % loc)
    listed = {local_target("sitemap.xml", l) for l in locs}
    for rel in sync_partials.PAGES:
        if rel not in listed:
            errors.append("sitemap.xml: %s is not listed" % rel)
    for thumb in re.findall(r"<video:(?:thumbnail|content)_loc>([^<]*)</video:", read("sitemap.xml")):
        target = local_target("sitemap.xml", thumb)
        if not os.path.exists(os.path.join(ROOT, target)):
            errors.append("sitemap.xml: video file %s missing" % thumb)


def check_videos(errors):
    vdir = os.path.join(ROOT, "assets", "video")
    for dirpath, _, files in os.walk(vdir):
        for f in files:
            if not f.endswith(".mp4"):
                continue
            path = os.path.join(dirpath, f)
            rel = os.path.relpath(path, ROOT)
            if os.path.getsize(path) > VIDEO_BUDGET:
                errors.append("%s: %.1f MB is over the %d MB budget" % (rel, os.path.getsize(path) / 1048576, VIDEO_BUDGET // 1048576))
            with open(path, "rb") as fh:
                head = fh.read(65536)
            moov, mdat = head.find(b"moov"), head.find(b"mdat")
            if moov == -1 or (mdat != -1 and mdat < moov):
                errors.append("%s: not encoded with -movflags +faststart" % rel)
            if not os.path.exists(path[:-4] + ".webp"):
                errors.append("%s: no poster image beside it" % rel)


def main():
    base = "main"
    if "--base" in sys.argv:
        base = sys.argv[sys.argv.index("--base") + 1]
    errors = []
    check_protected(base, errors)
    for rel in sync_partials.PAGES:
        text = read(rel)
        check_copy(rel, text, errors)
        check_links(rel, text, errors)
        check_jsonld(rel, text, errors)
        if sync_partials.render(rel, text) != text:
            errors.append("%s: shared partials out of date (run tools/sync_partials.py)" % rel)
    for rel in OWNED_TEXT:
        check_copy(rel, read(rel), errors)
    check_sitemap(errors)
    check_videos(errors)

    for e in errors:
        print(e)
    print("%d problem(s) in %d pages" % (len(errors), len(sync_partials.PAGES)) if errors
          else "ok: %d pages, protected files untouched, no price wording, links and sitemap resolve" % len(sync_partials.PAGES))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
