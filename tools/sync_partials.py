#!/usr/bin/env python3
"""Stamp the shared head, header and footer into every redesigned page.

Each page marks the managed regions with HTML comments:

    <!-- partial:head -->   ... <!-- /partial:head -->
    <!-- partial:header --> ... <!-- /partial:header -->
    <!-- partial:footer --> ... <!-- /partial:footer -->

Everything outside the markers is hand-written and left alone, so a page can
be edited directly; only the shared chrome comes from tools/partials/.

    python3 tools/sync_partials.py              # rewrite the regions
    python3 tools/sync_partials.py --check      # exit 1 if any page has drifted
    python3 tools/sync_partials.py index.html   # just the pages named

The privacy, terms and deletion pages are not in PAGES on purpose: they are
generated by documents/privacy/tools/build_privacy.py and must not change.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARTIALS = os.path.join(ROOT, "tools", "partials")
NAMES = ("head", "header", "footer")

PAGES = [
    "index.html",
    "contactus.html",
    "chinese/index.html",
    "chinese/chinese_contactus.html",
    "cantonese/index.html",
    "cantonese/cantonese_contactus.html",
    "english/index.html",
    "english/english_contactus.html",
    "gcd/guide/index.html",
    "xiezi/guide/index.html",
    "quickonescanner/index.html",
    "momerago/index.html",
    "momerago/zh-cn.html",
    "momerago/zh-tw.html",
    "mcmuse/index.html",
]


def page_url(rel):
    """The URL path a page is served at, as the header links spell it."""
    if rel == "index.html":
        return "/"
    if rel.endswith("/index.html"):
        return "/" + rel[: -len("index.html")]
    return "/" + rel


def render(rel, text):
    for name in NAMES:
        with open(os.path.join(PARTIALS, name + ".html"), encoding="utf-8") as fh:
            body = fh.read().strip("\n")
        if name == "header":
            # Mark the link to the page being viewed, if the header has one.
            body = body.replace('href="%s">' % page_url(rel),
                                'href="%s" aria-current="page">' % page_url(rel), 1)
        pattern = re.compile(r"(<!-- partial:%s -->)(.*?)(<!-- /partial:%s -->)" % (name, name), re.S)
        if not pattern.search(text):
            raise SystemExit("%s: missing <!-- partial:%s --> markers" % (rel, name))
        text = pattern.sub(lambda m: m.group(1) + "\n" + body + "\n" + m.group(3), text, count=1)
    return text


def main():
    check = "--check" in sys.argv[1:]
    only = [a for a in sys.argv[1:] if not a.startswith("--")]
    drifted = []
    for rel in only or PAGES:
        path = os.path.join(ROOT, rel)
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
        new = render(rel, old)
        if new != old:
            drifted.append(rel)
            if not check:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(new)
    if check:
        for rel in drifted:
            print("partials out of date: %s" % rel)
        return 1 if drifted else 0
    print("synced %d page(s)%s" % (len(drifted), (": " + ", ".join(drifted)) if drifted else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
